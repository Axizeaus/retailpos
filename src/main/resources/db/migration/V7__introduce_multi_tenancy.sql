DROP CONSTRAINT products_sku_key;

ALTER TABLE products
DROP CONSTRAINT uk_products_barcode;

ALTER TABLE sales
DROP CONSTRAINT sales_receipt_number_key;


ALTER TABLE categories
    ADD CONSTRAINT uk_categories_shop_name
        UNIQUE (shop_id, name);

ALTER TABLE products
    ADD CONSTRAINT uk_products_shop_sku
        UNIQUE (shop_id, sku);

ALTER TABLE products
    ADD CONSTRAINT uk_products_shop_barcode
        UNIQUE (shop_id, barcode);

ALTER TABLE sales
    ADD CONSTRAINT uk_sales_shop_receipt
        UNIQUE (shop_id, receipt_number);


-- These composite unique constraints let us reference an entity
-- using both its ID and its shop ID in a foreign key.
-- The ID is already unique, but PostgreSQL needs this exact pair
-- to be declared unique before we can use it as a composite FK.
ALTER TABLE categories
    ADD CONSTRAINT uk_categories_id_shop
        UNIQUE (id, shop_id);

ALTER TABLE products
    ADD CONSTRAINT uk_products_id_shop
        UNIQUE (id, shop_id);

ALTER TABLE sales
    ADD CONSTRAINT uk_sales_id_shop
        UNIQUE (id, shop_id);


-- The old single-column foreign keys are no longer enough.
-- Replace them with composite ones so records can't reference
-- categories, products or sales belonging to another shop.
ALTER TABLE products
DROP CONSTRAINT fk_products_category;

ALTER TABLE sale_items
DROP CONSTRAINT sale_items_sale_id_fkey;

ALTER TABLE sale_items
DROP CONSTRAINT sale_items_product_id_fkey;


-- A product's category must belong to the same shop as the product.
ALTER TABLE products
    ADD CONSTRAINT fk_products_category_shop
        FOREIGN KEY (category_id, shop_id)
            REFERENCES categories(id, shop_id);


-- A sale item must reference a sale and product from the same shop.
ALTER TABLE sale_items
    ADD CONSTRAINT fk_sale_items_sale_shop
        FOREIGN KEY (sale_id, shop_id)
            REFERENCES sales(id, shop_id);

ALTER TABLE sale_items
    ADD CONSTRAINT fk_sale_items_product_shop
        FOREIGN KEY (product_id, shop_id)
            REFERENCES products(id, shop_id);


-- These indexes help when fetching business data for a particular shop.
CREATE INDEX idx_categories_shop_id
    ON categories(shop_id);

CREATE INDEX idx_products_shop_category
    ON products(shop_id, category_id);

CREATE INDEX idx_sales_shop_created_at
    ON sales(shop_id, created_at DESC);

CREATE INDEX idx_sale_items_shop_sale
    ON sale_items(shop_id, sale_id);

CREATE INDEX idx_sale_items_shop_product
    ON sale_items(shop_id, product_id);
