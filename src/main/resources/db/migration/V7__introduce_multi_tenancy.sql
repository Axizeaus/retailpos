
-- Every shop gets its own data, so let's start with the shops table.
CREATE TABLE shops (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       name VARCHAR(150) NOT NULL,
                       slug VARCHAR(100) NOT NULL UNIQUE,
                       active BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- We've already got products and sales in the database.
-- Instead of leaving them orphaned, let's put everything under a demo shop.
INSERT INTO shops (name, slug)
VALUES ('Demo Shop', 'demo-shop');


-- Users are global accounts. They can belong to multiple shops.
CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email VARCHAR(254) NOT NULL,
                       password_hash VARCHAR(255) NOT NULL,
                       enabled BOOLEAN NOT NULL DEFAULT TRUE,
                       created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

-- Email addresses shouldn't be treated as different just because of casing.
CREATE UNIQUE INDEX uk_users_email_lower
    ON users (LOWER(email));


-- A membership connects a user to a shop and defines what they can do there.
CREATE TABLE shop_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    shop_id BIGINT NOT NULL REFERENCES shops(id),
    user_id BIGINT NOT NULL REFERENCES users(id),

    role VARCHAR(20) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    -- One user should only have one membership per shop.
    CONSTRAINT uk_shop_memberships_shop_user
        UNIQUE (shop_id, user_id),

    -- Keep roles limited to the ones our application actually supports.
    CONSTRAINT chk_shop_memberships_role
        CHECK (role IN ('OWNER', 'MANAGER', 'CASHIER'))
);

-- We'll often need to find all shops a user belongs to.
CREATE INDEX idx_shop_memberships_user_id
    ON shop_memberships(user_id);


-- Time to add shop ownership to the existing business tables.
-- Nullable for now because we need to backfill the existing records first.
ALTER TABLE categories ADD COLUMN shop_id BIGINT;
ALTER TABLE products ADD COLUMN shop_id BIGINT;
ALTER TABLE sales ADD COLUMN shop_id BIGINT;
ALTER TABLE sale_items ADD COLUMN shop_id BIGINT;


-- All existing data belongs to our demo shop for now.
UPDATE categories
SET shop_id = (SELECT id FROM shops WHERE slug = 'demo-shop');

UPDATE products
SET shop_id = (SELECT id FROM shops WHERE slug = 'demo-shop');

UPDATE sales
SET shop_id = (SELECT id FROM shops WHERE slug = 'demo-shop');

-- Sale items inherit their shop from the sale they belong to.
UPDATE sale_items si
SET shop_id = s.shop_id
    FROM sales s
WHERE si.sale_id = s.id;


-- Now that everything has an owner, shop_id can be mandatory.
ALTER TABLE categories ALTER COLUMN shop_id SET NOT NULL;
ALTER TABLE products ALTER COLUMN shop_id SET NOT NULL;
ALTER TABLE sales ALTER COLUMN shop_id SET NOT NULL;
ALTER TABLE sale_items ALTER COLUMN shop_id SET NOT NULL;


-- Make sure every shop_id points to an actual shop.
ALTER TABLE categories
    ADD CONSTRAINT fk_categories_shop
        FOREIGN KEY (shop_id) REFERENCES shops(id);

ALTER TABLE products
    ADD CONSTRAINT fk_products_shop
        FOREIGN KEY (shop_id) REFERENCES shops(id);

ALTER TABLE sales
    ADD CONSTRAINT fk_sales_shop
        FOREIGN KEY (shop_id) REFERENCES shops(id);

ALTER TABLE sale_items
    ADD CONSTRAINT fk_sale_items_shop
        FOREIGN KEY (shop_id) REFERENCES shops(id);


-- SKU, barcode, category name and receipt number only need to be unique
