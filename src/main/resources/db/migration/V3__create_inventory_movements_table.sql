CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    product_id BIGINT NOT NULL REFERENCES products(id),

    movement_type VARCHAR(30) NOT NULL,

    quantity_change INTEGER NOT NULL,
    quantity_before INTEGER NOT NULL,
    quantity_after INTEGER NOT NULL,

    note TEXT,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

ALTER TABLE inventory_movements
    ADD CONSTRAINT chk_inventory_movement_nonzero_change
        CHECK (quantity_change <> 0),
    ADD CONSTRAINT chk_inventory_movement_quantity_consistency
        CHECK (quantity_after = quantity_before + quantity_change),
    ADD CONSTRAINT chk_inventory_movement_nonnegative_stock
        CHECK (quantity_before >= 0 AND quantity_after >= 0);

CREATE INDEX idx_inventory_movements_product_created_at ON inventory_movements (product_id, created_at DESC)