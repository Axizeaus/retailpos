CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    receipt_number VARCHAR(40) NOT NULL UNIQUE,

    total_amount NUMERIC(12, 2) NOT NULL,
    cash_tendered NUMERIC(12, 2) NOT NULL,
    change_due NUMERIC(12, 2) NOT NULL,

    payment_method VARCHAR(30) NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT chk_sales_total_amount
        CHECK (total_amount > 0),

    CONSTRAINT chk_sales_cash_tendered
        CHECK (cash_tendered >= total_amount),

    CONSTRAINT chk_sales_change_due
        CHECK (change_due = cash_tendered - total_amount)
);